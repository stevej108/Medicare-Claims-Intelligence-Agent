def normalize_arguments(
    tool,
    arguments,
):
    if tool == ToolName.SEGMENT_COMPARISON:
        return {
            "segments": frozenset([
                arguments["segment_a"],
                arguments["segment_b"],
            ])
        }

    return arguments


@pytest.mark.llm
@pytest.mark.parametrize(
    "question, expected_tool, expected_arguments",
    ROUTING_CASES,
)
def test_question_routing(
    question,
    expected_tool,
    expected_arguments,
):
    route = route_question(question)

    assert route.tool == expected_tool

    if expected_tool == ToolName.KNOWLEDGE_SEARCH:
        assert set(
            route.arguments.keys()
        ) == {"query"}

        assert isinstance(
            route.arguments["query"],
            str,
        )

        assert route.arguments[
            "query"
        ].strip()

        return

    assert normalize_arguments(
        route.tool,
        route.arguments,
    ) == normalize_arguments(
        expected_tool,
        expected_arguments,
    )


def test_empty_question_fails():
    with pytest.raises(
        ValueError,
        match="question cannot be empty",
    ):
        route_question("   ")    



@pytest.mark.parametrize(
    "question",
    [
        "How is total annual cost calculated?",
        "How was the member-year analytical dataset constructed?",
        "Can these findings be generalized to real Medicare beneficiaries?",
        "How is Persistent High-Cost Complex defined?",
        "What does MEDREIMB_IP mean?",
        "What are the limitations of DE-SynPUF?",
    ],
)
def test_knowledge_questions_route_to_rag(
    question,
):
    route = route_question(question)

    assert (
        route.tool
        == ToolName.KNOWLEDGE_SEARCH
    )

    assert set(
        route.arguments.keys()
    ) == {"query"}

    assert route.arguments[
        "query"
    ].strip()    


